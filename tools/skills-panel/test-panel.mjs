import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const require = createRequire(import.meta.url);
const storage = new Map();
globalThis.localStorage = {getItem:key => storage.get(key) ?? null, setItem:(key,value) => storage.set(key,value)};
globalThis.window = {localStorage};
globalThis.location = new URL('http://localhost/index.html?painel=skills');
vm.runInThisContext(readFileSync('../../balance.js','utf8'));
const api = window.ScrewBalance;
assert.ok(api.catalog.length>=54,'all original skills remain in the expanded catalog');
assert.ok(api.validate(api.load()).ok);
const buildResult = await build({entryPoints:['App.tsx'],bundle:true,write:false,format:'cjs',platform:'node',jsx:'automatic',external:['react','react/jsx-runtime','lucide-react']});
function markup(component='default', props={}) {
  const module = {exports:{}};
  new Function('require','module','exports',buildResult.outputFiles[0].text)(require,module,module.exports);
  return renderToStaticMarkup(React.createElement(module.exports[component],props));
}
let html = markup();
assert.match(html,/Aplicar ao jogo/);
assert.ok(html.includes(`${api.catalog.length} resultados encontrados`));
assert.match(html,/ALTO IMPACTO/);
assert.match(html,/href="http:\/\/localhost\/index.html"/);
assert.match(html,/Raridade \(organizacional\)/);
assert.match(html,/Dano direto/);
const tree = markup('TalentTree',{skills:api.catalog,selectedId:'damage',onSelect:()=>{}});
for (const label of ['Normais sem requisitos','Normais com requisitos','Gambiarras · níveis 3/6/9','Especialização · nível 10','Após chefes','Grupos de oferta','Nível mínimo 1']) assert.ok(tree.includes(label),label);
assert.doesNotMatch(tree,/Fluxo de desbloqueio/);
assert.doesNotMatch(readFileSync('App.tsx','utf8'),/<span>Unidade<\/span>|aria-label="Sem unidade/);
assert.match(readFileSync('App.tsx','utf8'),/groupAccent\[skill.group\] \?\? skill.accent/);
storage.set('screwvivors.balance.draft.v1','{corrupt');
html = markup();
assert.match(html,/corrompido/);
assert.ok(html.includes(`${api.catalog.length} resultados encontrados`));
storage.set('screwvivors.balance.draft.v1',JSON.stringify({version:1,skills:[]}));
assert.match(markup(),/Rascunho inválido ignorado/);
const draft = structuredClone(api.load());
draft[0].name='TESTE RASCUNHO';
storage.set('screwvivors.balance.draft.v1',JSON.stringify({version:1,catalogRevision:3,skills:draft}));
assert.match(markup(),/TESTE RASCUNHO/);
assert.notEqual(api.load()[0].name,'TESTE RASCUNHO','draft cannot mutate applied storage');
Object.defineProperty(globalThis,'localStorage',{configurable:true,get(){throw Error('blocked');}});
assert.match(markup(),/indisponível ou corrompido/);
assert.doesNotMatch(readFileSync('panel.css','utf8'),/@import|https?:\/\//);
assert.doesNotMatch(readFileSync('App.tsx','utf8'),/window\.alert|skillforge-skills/);
console.log('Panel checks passed: real catalog, render, draft isolation, corrupt/unavailable storage, offline CSS.');
