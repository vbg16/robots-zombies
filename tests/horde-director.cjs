'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const bootstrap=fs.readFileSync('tests/combat.cjs','utf8').split('assert.match(')[0];
const {context}=new Function('require',bootstrap+';return {context};')(require);
const run=s=>vm.runInContext(s,context);
run('reset();drawMinimap=()=>{};updateHUD=()=>{};player.inv=1e9;bossIndex=1e6');
run('tick(1.99)');assert.equal(run('enemies.length'),0);
run('tick(.02)');assert.equal(run('enemies.length'),15);
run('globalThis.first=enemies.slice();');
for(let i=0;i<400;i++)run('tick(.1)');
assert.equal(run('enemies.length'),60,'idle opening never exceeds live cap');
assert.ok(run('first.every(z=>enemies.includes(z))'),'cap never deletes survivors');
run('enemies.splice(0,8);kills+=8;spawn=6;hordeDirector.cooldown=0;tick(.01)');
assert.equal(run('enemies.length'),60,'kill trigger fills exactly available capacity');
assert.equal(run('hordeDirector.lastReason'),'kills');
run('enemies.splice(0,15);kills+=15;tick(.01)');assert.equal(run('enemies.length'),45,'kill bursts cannot bypass cooldown');
run('tick(3)');assert.equal(run('enemies.length'),60);
run('globalThis.witness=enemies[0];witness.hp=13;witness.shieldHp=37;globalThis.oldCount=enemies.length;player.x+=5000;syncCamera();hordeDirector.cooldown=0;tick(.01)');
assert.equal(run('hordeDirector.lastReason'),'travel');assert.equal(run('enemies.length'),60);
assert.equal(run('witness.hp'),13);assert.equal(run('witness.shieldHp'),37);
assert.ok(run('Math.hypot(witness.x-player.x,witness.y-player.y)<waveRadius()*1.1'),'distant pursuer re-enters ahead of the new region');
assert.ok(run('witness.x+50<camera.x||witness.x-50>camera.x+width||witness.y+60<camera.y||witness.y-60>camera.y+height'),'re-entry stays entirely outside view');
run('clock=300;hordeDirector.cooldown=0;spawn=0;tick(.01)');assert.equal(run('hordePopulationLimit()'),120);assert.equal(run('enemies.length'),75);
run('clock=3600');assert.equal(run('hordePopulationLimit()'),180,'late game has a hard bound');
run('state="paused";globalThis.before=JSON.stringify(hordeDirector);tick(10)');assert.equal(run('JSON.stringify(hordeDirector)'),run('before'),'pause freezes director');
run('reset()');assert.equal(run('hordeDirector.lastKills'),0);assert.equal(run('hordeDirector.cooldown'),2);
run('player.inv=1e9;bossIndex=1e6;globalThis.maxCommon=0;globalThis.nearFrames=0;');
for(let i=0;i<3000;i++)run('player.x+=19;tick(.1);maxCommon=Math.max(maxCommon,enemies.length);if(enemies.some(z=>Math.hypot(z.x-player.x,z.y-player.y)<waveRadius()*1.4))nearFrames++;');
assert.ok(run('maxCommon<=120'),'five-minute fleeing remains bounded');
assert.ok(run('nearFrames>2500'),'running continually retains nearby encounters');
console.log('Director: initial circle, live cap, kill cooldown, travel re-entry, HP/shield preservation, pause/reset and five-minute flight passed.');
